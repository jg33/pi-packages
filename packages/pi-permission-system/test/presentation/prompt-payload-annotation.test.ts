import { describe, expect, expectTypeOf, it } from "vitest";
import {
  asPromptPayload,
  type MODEL_GENERATED,
  modelGeneratedAnnotation,
  type PromptAnnotation,
} from "#src/presentation/prompt-payload";
import { makePromptPayload } from "#test/helpers/prompt-details-fixtures";

describe("PromptAnnotation", () => {
  it("is marked model-generated by its constructor", () => {
    expect(modelGeneratedAnnotation("echo", "hi")).toEqual({
      source: "echo",
      text: "hi",
      marking: "model-generated",
    });
    expectTypeOf<PromptAnnotation["marking"]>().toEqualTypeOf<
      typeof MODEL_GENERATED
    >();
  });

  // Keep each flagged declaration on ONE line: `@ts-expect-error` covers only
  // the next line, and tsc reports a bad property on the property's own line.
  it("cannot be built unmarked or marked as anything else", () => {
    const human = "human-written" as const;
    // @ts-expect-error -- an unmarked annotation is unrepresentable
    const unmarked: PromptAnnotation = { source: "echo", text: "hi" };
    // @ts-expect-error -- so is any marking but the one this package owns
    const other: PromptAnnotation = { source: "e", text: "h", marking: human };
    expect([unmarked, other]).toHaveLength(2);
  });

  it("re-stamps the marking when a serialized payload is read back", () => {
    const wire = {
      ...makePromptPayload(),
      annotations: [
        { source: "echo", text: "hi", marking: "human-written" },
        { source: "older-child", text: "no marking at all" },
      ],
    };
    expect(asPromptPayload(wire)?.annotations).toEqual([
      modelGeneratedAnnotation("echo", "hi"),
      modelGeneratedAnnotation("older-child", "no marking at all"),
    ]);
  });
});
